#!/usr/bin/env python3
"""Generate the app-local opengl32.dll proxy sources.

The proxy exports exactly the functions that the game actually imports from
opengl32, each as a naked jump to a slot filled in with the real address from
the system library. Nothing else is exported, so the proxy cannot accidentally
shadow behaviour the game relies on.

Two modes:

  --imports-from <pe>   Parse the import table of a PE file and emit every
                        function it imports from opengl32.dll. Point this at
                        RenderOpenGL.dll for the precise minimum.
  --exports-of <pe>     Emit every named export of the given PE. Use this with
                        the system opengl32.dll for a full-surface proxy.

Writes the C++ translation unit and the .def only when their content changed,
so a build tree is never touched by a no-op regeneration.
"""

import argparse
import struct
import sys
from pathlib import Path


class PE:
    def __init__(self, data: bytes):
        self.data = data
        if data[:2] != b"MZ":
            raise ValueError("not a PE file (missing MZ)")
        self.pe_off = struct.unpack_from("<I", data, 0x3C)[0]
        if data[self.pe_off:self.pe_off + 4] != b"PE\0\0":
            raise ValueError("not a PE file (missing PE signature)")

        coff = self.pe_off + 4
        self.machine, self.num_sections = struct.unpack_from("<HH", data, coff)
        size_opt = struct.unpack_from("<H", data, coff + 16)[0]
        self.opt_off = coff + 20

        magic = struct.unpack_from("<H", data, self.opt_off)[0]
        if magic == 0x10B:
            self.is_pe32 = True
            dir_off = self.opt_off + 96
        elif magic == 0x20B:
            self.is_pe32 = False
            dir_off = self.opt_off + 112
        else:
            raise ValueError(f"unknown optional header magic 0x{magic:x}")
        self.data_dirs = dir_off

        sec_off = self.opt_off + size_opt
        self.sections = []
        for i in range(self.num_sections):
            base = sec_off + i * 40
            name = data[base:base + 8].rstrip(b"\0").decode("ascii", "replace")
            vsize, vaddr, rsize, raddr = struct.unpack_from("<IIII", data, base + 8)
            self.sections.append((name, vaddr, vsize, raddr, rsize))

    def rva_to_off(self, rva: int) -> int:
        for _name, vaddr, vsize, raddr, rsize in self.sections:
            span = max(vsize, rsize)
            if vaddr <= rva < vaddr + span:
                return raddr + (rva - vaddr)
        raise ValueError(f"rva 0x{rva:x} is not inside any section")

    def cstr(self, rva: int) -> str:
        off = self.rva_to_off(rva)
        end = self.data.index(b"\0", off)
        return self.data[off:end].decode("ascii", "replace")

    def data_dir(self, index: int):
        off = self.data_dirs + index * 8
        return struct.unpack_from("<II", self.data, off)

    def imports(self):
        """Yield (dll_name_lower, [name or ordinal, ...])."""
        rva, _size = self.data_dir(1)  # IMAGE_DIRECTORY_ENTRY_IMPORT
        if rva == 0:
            return
        off = self.rva_to_off(rva)
        stride_entry = 4 if self.is_pe32 else 8
        high = 1 << (31 if self.is_pe32 else 63)
        while True:
            ilt, _ts, _fc, name_rva, _ft = struct.unpack_from("<IIIII", self.data, off)
            if ilt == 0 and name_rva == 0:
                return
            if ilt == 0:
                off += 20
                continue
            dll = self.cstr(name_rva).lower()
            entries = []
            cur = self.rva_to_off(ilt)
            while True:
                if self.is_pe32:
                    value, = struct.unpack_from("<I", self.data, cur)
                else:
                    value, = struct.unpack_from("<Q", self.data, cur)
                if value == 0:
                    break
                entries.append((value & 0xFFFF) if value & high else self.cstr(value + 2))
                cur += stride_entry
            yield dll, entries
            off += 20

    def exports(self):
        rva, _size = self.data_dir(0)  # IMAGE_DIRECTORY_ENTRY_EXPORT
        if rva == 0:
            return []
        off = self.rva_to_off(rva)
        fields = struct.unpack_from("<IIHHIIIIIII", self.data, off)
        n_names, addr_names = fields[7], fields[9]
        names = []
        for i in range(n_names):
            nrva, = struct.unpack_from("<I", self.data, self.rva_to_off(addr_names) + i * 4)
            names.append(self.cstr(nrva))
        return names


CPP_HEADER = """\
// Generated by tools/gen_opengl32_proxy.py - do not edit by hand.
//
// Source: {source}
// Count : {count}
//
// Each export is a naked thunk: it forwards the caller's arguments untouched
// to the matching function in the system opengl32.dll. A thunk whose slot has
// not been resolved returns zero without disturbing the stack.
//
// The slot table and name table use C linkage deliberately: MSVC's inline
// assembler resolves plain identifiers, not namespaced C++ symbols.

#include "proxy_slots.h"

// Zero-initialised definition: a bare `extern "C" T x[N];` would only be a
// declaration in C++, leaving the symbol with no storage.
extern "C" void* {slots_name}[{count}] = {{}};

extern "C" {{

"""

CPP_THUNK = """\
__declspec(naked) void {name}() {{
    __asm {{
        mov eax, dword ptr [{slots_name} + {offset}]
        test eax, eax
        jne h47vr_go_{name}
        call dword ptr [h47vr_proxy_resolve_fn]
        mov eax, dword ptr [{slots_name} + {offset}]
        test eax, eax
        jne h47vr_go_{name}
        xor eax, eax
        ret
    h47vr_go_{name}:
        jmp eax
    }}
}}

"""

CPP_FOOTER = """\
}}  // extern "C"

// Deliberately non-const objects: a const-qualified namespace-scope variable
// would take internal linkage and the proxy and resolver could not share it.
extern "C" const char* {names_name}[{count}] = {{
{names}
}};

extern "C" int {count_name} = {count};
"""

DEF_HEADER = """\
; Generated by tools/gen_opengl32_proxy.py - do not edit by hand.
LIBRARY opengl32
EXPORTS
"""

def gather(args):
    if args.imports_from:
        pe = PE(Path(args.imports_from).read_bytes())
        wanted = (args.import_dll or "opengl32.dll").lower()
        names, ordinals = [], []
        for dll, entries in pe.imports():
            if dll != wanted:
                continue
            for entry in entries:
                (ordinals if isinstance(entry, int) else names).append(entry)
        if ordinals:
            raise SystemExit(
                "imports by ordinal cannot be forwarded by name: "
                + ", ".join(str(o) for o in sorted(set(ordinals)))
                + "\nUse --exports-of on the real opengl32.dll instead."
            )
        return sorted(set(names)), f"imports of {wanted} in {Path(args.imports_from).name}"

    if args.exports_of:
        pe = PE(Path(args.exports_of).read_bytes())
        return sorted(set(pe.exports())), f"named exports of {Path(args.exports_of).name}"

    raise SystemExit("one of --imports-from or --exports-of is required")


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\r\n")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--imports-from")
    ap.add_argument("--import-dll", default="opengl32.dll")
    ap.add_argument("--exports-of")
    ap.add_argument("--slots-name", default="g_slots")
    ap.add_argument("--names-name", default="g_names")
    ap.add_argument("--count-name", default="g_count")
    ap.add_argument("--cpp", required=True)
    ap.add_argument("--def", required=True, dest="def_path")
    args = ap.parse_args()

    names, source = gather(args)
    if not names:
        raise SystemExit("no functions found")

    body = "".join(
        CPP_THUNK.format(name=n, slots_name=args.slots_name, offset=i * 4)
        for i, n in enumerate(names)
    )
    names_block = "".join(f'    "{n}",\n' for n in names)
    cpp = (
        CPP_HEADER.format(source=source, count=len(names), slots_name=args.slots_name)
        + body
        + CPP_FOOTER.format(
            count=len(names),
            names=names_block,
            names_name=args.names_name,
            count_name=args.count_name,
        )
    )
    def_text = DEF_HEADER + "".join(f"    {n}\n" for n in names)

    changed = [
        p for p, text in ((Path(args.cpp), cpp), (Path(args.def_path), def_text))
        if write_if_changed(p, text)
    ]
    print(f"{len(names)} exports from {source}")
    print("updated: " + (", ".join(str(c) for c in changed) if changed else "nothing"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
